let activeLocale = LOCALES.en;

// "auto" follows the browser language and falls back to English.
function setLanguage(choice) {
  let code = choice;
  if (!Object.hasOwn(LOCALES, code)) {
    code = browser.i18n.getUILanguage().slice(0, 2).toLowerCase();
  }
  if (!Object.hasOwn(LOCALES, code)) code = "en";
  activeLocale = LOCALES[code];
  document.documentElement.lang = code;
}

function t(key, ...subs) {
  const text = activeLocale[key] ?? LOCALES.en[key] ?? key;
  return text.replace(/\$(\d)/g, (_, n) => subs[n - 1] ?? "");
}

// Fills every element carrying data-i18n / data-i18n-placeholder.
function localizeDocument() {
  for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
}
